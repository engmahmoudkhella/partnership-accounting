class _SafeDict(dict):
    def __missing__(self, key):
        return "{" + key + "}"


def tr(lang: str, key: str, **params) -> str:
    pair = T.get(key)
    if pair is None:
        return key
    text = pair[0] if lang == "ar" else pair[1]
    if params:
        try:
            text = text.format_map(_SafeDict(params))
        except (ValueError, IndexError):
            pass
    return text
